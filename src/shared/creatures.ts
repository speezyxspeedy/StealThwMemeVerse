export const CREATURE_BY_ID: Record<string, CreatureDefinition> = Object.fromEntries(
  CREATURES.map((c) => [c.id, c]),
);

export function getCreatureEffectiveIncome(
  creatureId: string,
  mutation: MutationType,
  level = 1,
): number {
  const def = CREATURE_BY_ID[creatureId];
  if (!def) return 0;
  const mutMult = MUTATION_META[mutation]?.multiplier ?? 1;
  const lvlMult = 1 + (Math.max(1, level) - 1) * 0.35;
  return Math.round(def.incomePerSec * mutMult * lvlMult);
}

export function getCreatureSellValue(
  creatureId: string,
  mutation: MutationType,
  level = 1,
): number {
  const def = CREATURE_BY_ID[creatureId];
  if (!def) return 0;
  const mutMult = MUTATION_META[mutation]?.multiplier ?? 1;
  const lvlMult = 1 + (Math.max(1, level) - 1) * 0.4;
  return Math.round(def.price * 0.65 * mutMult * lvlMult);
}

export function rollCreature(luckMultiplier = 1): CreatureDefinition {
  const weighted = CREATURES.map((c) => {
    const rarityOrder = RARITY_META[c.rarity].order;
    const boost = rarityOrder >= 4 ? Math.pow(luckMultiplier, (rarityOrder - 3) * 0.55) : 1;
    return { creature: c, weight: c.spawnWeight * boost };
  });
  const total = weighted.reduce((acc, w) => acc + w.weight, 0);
  let r = Math.random() * total;
  for (const entry of weighted) {
    r -= entry.weight;
    if (r <= 0) return entry.creature;
  }
  return CREATURES[0];
}

export function rollMutation(luckMultiplier = 1, forceRareMutation = false): MutationType {
  const entries = Object.values(MUTATION_META);
  const weighted = entries.map((m) => {
    if (m.type === 'normal') {
      return { type: m.type, weight: forceRareMutation ? 0 : m.weight };
    }
    return { type: m.type, weight: m.weight * luckMultiplier };
  });
  const total = weighted.reduce((acc, w) => acc + w.weight, 0);
  let r = Math.random() * total;
  for (const entry of weighted) {
    r -= entry.weight;
    if (r <= 0) return entry.type;
  }
  return 'normal';
}

export function formatNumber(n: number): string {
  if (!Number.isFinite(n)) return '0';
  const abs = Math.abs(n);
  if (abs >= 1_000_000_000) return `${(n / 1_000_000_000).toFixed(2)}B`;
  if (abs >= 1_000_000) return `${(n / 1_000_000).toFixed(2)}M`;
  if (abs >= 10_000) return `${(n / 1_000).toFixed(1)}K`;
  return Math.floor(n).toLocaleString('en-US');
}
